// One Polish letter and the font code a game draws it with. A letter the
// font lacks names a plain one instead (e.g. 'A' for capital A-ogonek).
struct Letter {
    char32_t letter;
    unsigned char code;
};

// Installs kTable for a game whose font draws Polish letters at `letters`.
// The converted text is kept for the life of the program (the menu keeps
// pointers into it). Other characters pass through; a non-ASCII character
// not in `letters` becomes '?', so a missing slot shows instead of a wrong
// letter.
template <std::size_t N>
void install(const Letter (&letters)[N]) {
    static std::vector<std::string> texts;
    static std::vector<gbarecomp::UiTranslation> table;
    texts.clear();
    table.clear();
    texts.reserve(std::size(kTable));
    for (const auto& row : kTable) {
        std::string out;
        const auto* s = reinterpret_cast<const unsigned char*>(row.text);
        while (*s) {
            char32_t c = *s++;
            if (c >= 0x80u) {
                const int extra = c >= 0xF0u ? 3 : c >= 0xE0u ? 2 : 1;
                c &= extra == 3 ? 0x07u : extra == 2 ? 0x0Fu : 0x1Fu;
                for (int i = 0; i < extra && (*s & 0xC0u) == 0x80u; ++i) c = (c << 6) | (*s++ & 0x3Fu);
                unsigned char code = '?';
                for (const Letter& l : letters)
                    if (l.letter == c) code = l.code;
                c = code;
            }
            // The font code, as UTF-8 (the menus read Latin-1 code points).
            if (c < 0x80u) out += static_cast<char>(c);
            else {
                out += static_cast<char>(0xC0u | (c >> 6));
                out += static_cast<char>(0x80u | (c & 0x3Fu));
            }
        }
        texts.push_back(std::move(out));
    }
    for (std::size_t i = 0; i < std::size(kTable); ++i)
        table.push_back({kTable[i].english, texts[i].c_str()});
    gbarecomp::config_ui_set_translations(table.data(), static_cast<int>(table.size()));
}

