"""Build the sound mixer's self-patched code variants for gba_recompile.

The boot IWRAM copy (ROM 0x080006B8 -> 0x03000100, 0x1000 bytes) holds a
mixer that writes instructions into its own loops. Each patched spot has a
small, fixed set of possible contents, all made from template words the
copy itself carries (FACTS.md, 2026-10-03):

  A  0x0300096C copies one of three 6-word templates (0x03000AFC + 0x18*k)
     into the eight slots of the loop 0x030009A4..0x03000AE8: words 0-1 to
     slot+4, words 2-5 to slot+0x10, slots at 0x030009A8 + 0x24*i and
     0x030009A8 + 0x98 + 0x24*i, i = 0..3. Checked against a live IWRAM dump
     (template 1 matched byte for byte).
  B  0x03000C40 copies 8 words from 0x03000BE0 + 8*(r3 & 3) into the holes
     at 0x03000C7C, 0x03000C88, 0x03000C94, 0x03000CA0 (2 words each) of
     0x03000C78..0x03000CBC: four variants.
  C  0x03000D58..0x03000D60 stores the word at 0x03000E88 or 0x03000E8C to
     0x03000E64 (a `bgt`). The second is the ROM's own word, so only the
     first needs a variant of 0x03000E60..0x03000E88.

For each variant this writes, under --out/<name>/:
  variant.gba   the ROM with that variant applied at the copy's source bytes
  variant.toml  gba_recompile config for the region (position-independent
                image at its own fixed address)
  expected.cpp  the region's bytes, for the runner's identity check
All output is ROM-derived and belongs under local/ (gitignored).

Usage: python tools/tla_mixer_variants.py --rom <rom> --out local/tla/variants
"""
import argparse
import hashlib
import os

ROM_SHA1 = "b500663220cb9bf56b9f8e8c0c544f1d6fa3a824"
COPY_RUNTIME = 0x03000100
COPY_SOURCE = 0x080006B8


def rom_off(runtime):
    return runtime - COPY_RUNTIME + COPY_SOURCE - 0x08000000


def words(rom, runtime, n):
    o = rom_off(runtime)
    return rom[o:o + 4 * n]


def variants(rom):
    out = []
    # A
    for k in range(3):
        t = words(rom, 0x03000AFC + 0x18 * k, 6)
        patches = []
        for i in range(4):
            for slot in (0x030009A8 + 0x24 * i, 0x030009A8 + 0x98 + 0x24 * i):
                patches.append((slot + 4, t[0:8]))
                patches.append((slot + 0x10, t[8:24]))
        out.append(("mixa%d" % k, 0x030009A4, 0x03000AE8, patches,
                    "template %d at 0x%08X copied by 0x0300096C into the "
                    "eight slots" % (k, 0x03000AFC + 0x18 * k)))
    # B
    for k in range(4):
        t = words(rom, 0x03000BE0 + 8 * k, 8)
        patches = [(dst, t[8 * j:8 * j + 8]) for j, dst in
                   enumerate((0x03000C7C, 0x03000C88, 0x03000C94, 0x03000CA0))]
        out.append(("mixb%d" % k, 0x03000C78, 0x03000CBC, patches,
                    "window %d (0x%08X) copied by 0x03000C40 into the four "
                    "holes" % (k, 0x03000BE0 + 8 * k)))
    # C
    out.append(("mixc1", 0x03000E60, 0x03000E88,
                [(0x03000E64, words(rom, 0x03000E88, 1))],
                "word at 0x03000E88 stored to 0x03000E64 by 0x03000D60"))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rom", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    rom = open(args.rom, "rb").read()
    if hashlib.sha1(rom).hexdigest() != ROM_SHA1:
        raise SystemExit("unexpected ROM")
    for name, start, end, patches, why in variants(rom):
        img = bytearray(rom)
        for dst, data in patches:
            o = rom_off(dst)
            img[o:o + len(data)] = data
        d = os.path.join(args.out, name)
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, "variant.gba"), "wb").write(img)
        size = end - start
        src = rom_off(start) + 0x08000000
        open(os.path.join(d, "variant.toml"), "w", newline="\n").write(
            '''# GENERATED by tools/tla_mixer_variants.py -- do not edit or commit.
# Mixer variant %s: %s.
[program]
name = "Golden Sun: The Lost Age mixer variant %s"
id = "golden_sun_tla_%s"
load_address = 0x08000000
size = 0x01000000
entry_pc = 0x%08X
speculative_literal_harvest = false
codegen_shards = 1

[identity]
sha1 = "%s"

[[code_copy]]
runtime_start = 0x%08X
source_start = 0x%08X
size = 0x%08X
name = "%s"
note = "self-patched mixer region"

[[extra_func]]
addr = 0x%08X
mode = "arm"
name = "%s_entry"
note = "region start"

[[resume_range]]
start = 0x%08X
end = 0x%08X
mode = "arm"
note = "every instruction is an entry"
''' % (name, why, name, name, start, hashlib.sha1(img).hexdigest(), start,
       src, size, name, start, name, start + 4, end))
        data = img[rom_off(start):rom_off(start) + size]
        with open(os.path.join(d, "expected.cpp"), "w", newline="\n") as f:
            f.write("// GENERATED by tools/tla_mixer_variants.py -- ROM-derived.\n")
            f.write("#include <cstdint>\n")
            f.write('extern "C" const uint8_t %s_kExpected[] = {\n' % name)
            for i in range(0, size, 16):
                f.write("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",\n")
            f.write("};\n")
        print("%s 0x%08X:%X" % (name, start, size))


if __name__ == "__main__":
    main()
