#!/usr/bin/env python3
"""Shared Windows/Linux ROM translation pipeline. Outputs remain in local/."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
from datetime import datetime
from tla_rom_revisions import identify

ROOT = Path(__file__).resolve().parents[1]
SHA1 = "b500663220cb9bf56b9f8e8c0c544f1d6fa3a824"


def run(*args, capture=False):
    result = subprocess.run([str(a) for a in args], check=True,
                            stdout=subprocess.PIPE if capture else None,
                            text=True, cwd=ROOT)
    return result.stdout.splitlines() if capture else []


def helper(name, *args):
    return run(sys.executable, ROOT / "tools" / name, *args, capture=True)


def generate(rom, recompiler, output, cache, harvest_ram_code=True):
    rom_sha1,revision=identify(rom.read_bytes())
    config_root=ROOT/"config"/revision["config"]
    # Check dependencies before replacing any generated output.
    import unicorn  # noqa: F401
    import capstone  # noqa: F401

    archive=ROOT.parent/"Archive"/"tla-regeneration"/datetime.now().strftime("%Y%m%d-%H%M%S-%f")
    archived=[]

    def fresh(name):
        path = output / name
        if path.exists():
            path.resolve().relative_to(ROOT/"local")
            archive.mkdir(parents=True,exist_ok=True)
            destination=archive/name
            destination.resolve().relative_to((ROOT.parent/"Archive").resolve())
            shutil.move(str(path),str(destination))
            archived.append(dict(source=str(path),archive=str(destination)))
            (archive/"manifest.json").write_text(json.dumps(archived,indent=2)+"\n",encoding="utf-8")
        path.mkdir(parents=True)
        return path

    main, reloc = fresh("main"), fresh("reloc")
    run(recompiler, "--rom", rom, "--config", config_root / "main.toml",
        "--out", main)
    lines = ["// GENERATED by tools/tla_recompile.py from config/tla/reloc/*.toml."]

    def image(name, source_rom, config, spec):
        dest = reloc / name
        dest.mkdir()
        run(recompiler, "--rom", source_rom, "--config", config, "--out", dest,
            "--relocatable-image", spec.removeprefix("0x"),
            "--symbol-prefix", name + "_", capture=True)
        return dest

    selfpatch = fresh("selfpatch")
    patched = helper("tla_selfpatch_rom.py", "--rom", rom, "--configs",
                     config_root / "reloc", "--out", selfpatch)
    for config in sorted((config_root / "reloc").glob("*.toml")):
        text = config.read_text()
        name = config.stem
        origin = re.search(r"runtime_start\s*=\s*(0x[0-9A-Fa-f]+)", text)
        source = re.search(r"source_start\s*=\s*(0x[0-9A-Fa-f]+)", text)
        sizes = re.findall(r"^size\s*=\s*(0x[0-9A-Fa-f]+)", text, re.M)
        if not origin or not source or not sizes:
            raise ValueError(f"{config.name}: missing code_copy origin/source/size.")
        spec = origin[1][2:] + ":" + sizes[-1][2:]
        image(name, selfpatch / "selfpatch.gba" if name in patched else rom,
              selfpatch / (name + ".toml") if name in patched else config, spec)
        lines.append(f"TLA_RELOC({name}, {source[1]}u)")
        for start, end in re.findall(
                r"^# identity-skip (0x[0-9A-Fa-f]+):(0x[0-9A-Fa-f]+)", text, re.M):
            lines.append(f"TLA_SKIP({name}, {start}u, {end}u)")

    variants = fresh("variants")
    for line in helper("tla_mixer_variants.py", "--rom", rom, "--out", variants):
        name, spec = line.split()
        src = variants / name
        dest = image(name, src / "variant.gba", src / "variant.toml", spec)
        shutil.copyfile(src / "expected.cpp", dest / "expected.cpp")
        lines.append(f"TLA_VARIANT({name})")

    blitters = fresh("blitters")
    for line in helper("tla_battle_blitters.py", "--rom", rom, "--out", blitters):
        name, spec = line.split()
        src = blitters / name
        dest = image(name, blitters / "blitters.gba", src / "variant.toml", spec)
        shutil.copyfile(src / "expected.cpp", dest / "expected.cpp")
        lines.append(f"TLA_FAMILY({name})")

    # Both platforms retain the same measured cache harvest, even after clearing it.
    keep = ROOT / "local" / revision["corpus"] / "pieces"
    (keep / rom_sha1).mkdir(parents=True, exist_ok=True)
    for pic in cache.rglob("*.pic"):
        if rom_sha1 not in pic.parts:
            continue
        destination=keep / rom_sha1 / pic.name
        if pic.resolve()!=destination.resolve(): shutil.copyfile(pic,destination)
    harvest = fresh("harvest")
    # --no-harvest: no harv families, as a build with "Pre-built RAM code" off
    # (TLA_NO_HARVEST) compiles none; the pieces above are still kept.
    for line in (helper("tla_harvest.py", "--rom", rom, "--cache", keep, "--out", harvest)
                 if harvest_ram_code else []):
        name, spec = line.split()
        src = harvest / name
        dest = image(name, harvest / "harvest.gba", src / "variant.toml", spec)
        shutil.copyfile(src / "expected.cpp", dest / "expected.cpp")
        lines.append(f"TLA_HARVEST({name})")

    (reloc / "tla_reloc_images.inc").write_text("\n".join(lines) + "\n", encoding="ascii")
    for folder in (main, reloc):
        run(sys.executable, ROOT.parent / "scripts/slim_corpus.py", folder)
    (main / ".complete").write_text(rom_sha1 + "\n", encoding="ascii")
    print(f"Generated {len(lines) - 1} RAM image entries in {reloc}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rom", type=Path)
    parser.add_argument("--recompile", type=Path)
    parser.add_argument("--out", type=Path, default=ROOT / "local/tla")
    parser.add_argument("--cache", type=Path, default=ROOT / "recomp_cache")
    parser.add_argument("--no-harvest", action="store_true",
                        help="leave out the harvested RAM code (Pre-built RAM code off)")
    args = parser.parse_args()
    try:
        config = {}
        if not args.rom or not args.recompile:
            config = json.loads((ROOT / "config/local.json").read_text(encoding="utf-8-sig"))
        rom = (args.rom or Path(config["rom"])).resolve()
        recompiler = (args.recompile or Path(config["recompile"])).resolve()
        output = args.out.resolve()
        if not output.is_relative_to(ROOT / "local") or output == ROOT / "local":
            raise ValueError("Generated output must be a directory inside this repository's local/.")
        if not recompiler.is_file():
            raise ValueError("Recompiler not found; build gba_recompile first.")
        generate(rom, recompiler, output, args.cache.resolve(), not args.no_harvest)
        return 0
    except (OSError, ValueError, KeyError, ImportError, subprocess.CalledProcessError) as error:
        print(f"tla_recompile: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
