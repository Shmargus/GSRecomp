inline void blend_px(uint8_t* p, uint8_t r, uint8_t g, uint8_t b,
                     uint8_t shade) {
    if (shade == 255) {
        p[0] = r; p[1] = g; p[2] = b;
        return;
    }
    const unsigned inv = 255u - shade;
    p[0] = static_cast<uint8_t>((r * shade + p[0] * inv) / 255u);
    p[1] = static_cast<uint8_t>((g * shade + p[1] * inv) / 255u);
    p[2] = static_cast<uint8_t>((b * shade + p[2] * inv) / 255u);
}

char to_upper_ascii(char c) {
    return (c >= 'a' && c <= 'z') ? static_cast<char>(c - 'a' + 'A') : c;
}

