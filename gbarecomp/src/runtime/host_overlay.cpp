void overlay_fill(uint8_t* rgb, int w, int h, int x, int y, int rw, int rh,
                  uint8_t r, uint8_t g, uint8_t bl, uint8_t shade) {
    if (!rgb || shade == 0) return;
    for (int py = y; py < y + rh; ++py) {
        if (py < 0 || py >= h) continue;
        for (int px = x; px < x + rw; ++px) {
            if (px < 0 || px >= w) continue;
            blend_px(rgb + (static_cast<std::size_t>(py) * w + px) * 3u,
                     r, g, bl, shade);
        }
    }
}

void overlay_text(uint8_t* rgb, int w, int h, int x, int y, const char* s,
                  uint8_t r, uint8_t g, uint8_t bl) {
    if (!rgb || !s) return;
    int cx = x;
    for (; *s; ++s, cx += 8) {
        char c = to_upper_ascii(*s);
        if (c < 32 || c > 95) c = ' ';
        const uint8_t* glyph = kFont[static_cast<int>(c) - 32];
        if (cx >= w) break;
        for (int row = 0; row < 8; ++row) {
            const int py = y + row;
            if (py < 0 || py >= h) continue;
            uint8_t bits = glyph[row];
            for (int col = 0; col < 5; ++col) {
                if (!(bits & (0x80u >> col))) continue;
                const int px = cx + col;
                if (px < 0 || px >= w) continue;
                blend_px(rgb + (static_cast<std::size_t>(py) * w + px) * 3u,
                         r, g, bl, 255);
            }
        }
    }
}

int overlay_text_width(const char* s) {
    if (!s) return 0;
    return static_cast<int>(std::strlen(s)) * 8;
}

